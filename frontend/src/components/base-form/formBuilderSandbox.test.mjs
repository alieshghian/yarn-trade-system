import test from 'node:test'
import assert from 'node:assert/strict'
import * as sandbox from './formBuilderSandboxState.ts'

test('independent phone instances preserve labels, position and demo values across save/restore; deletion and invalid storage are safe', () => {
  const preset = { id: 'contact.phone', componentId: 'base-form.value-list', title: { fa: 'تلفن', en: 'Phone', zh: '电话' }, schemaKind: 'valueList', labelPolicy: 'editable', allowedFormTypes: ['operational', 'hybrid'] }
  const original = sandbox.emptySandboxForm()
  let form = sandbox.addSandboxPhone(original, preset, 'phone-instance-1')
  form = sandbox.addSandboxPhone(form, preset, 'phone-instance-2')
  assert.equal(original.fields.length, 0)
  assert.notEqual(form.fields[0].id, form.fields[1].id)
  assert.equal(form.fields[0].componentId, form.fields[1].componentId)
  assert.throws(() => sandbox.addSandboxPhone(form, preset, 'phone-instance-1'), /unique/)
  assert.throws(() => sandbox.addSandboxPhone(form, { ...preset, id: 'contact.mobile' }, 'mobile'), /no sandbox adapter/)
  form = sandbox.updateSandboxPhone(form, 'phone-instance-1', field => ({ ...field, label: { ...field.label, fa: 'تلفن دفتر' }, settings: { ...field.settings, demo: { primary: '0215555000', listPrimary: '0215555000', numbers: ['0215555000', '0215555001'] } } }))
  form = sandbox.moveSandboxPhone(form, 'phone-instance-1', 160, 210)
  const values = new Map([['laboratory-existing-key', 'unchanged']])
  const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) }
  assert.equal(sandbox.saveSandboxForm(storage, form), true)
  assert.deepEqual(sandbox.loadSandboxForm(storage), form)
  assert.equal(values.get('laboratory-existing-key'), 'unchanged')
  assert.deepEqual([...values.keys()], ['laboratory-existing-key', sandbox.sandboxStorageKey])
  const restored = sandbox.loadSandboxForm(storage)
  assert.equal(restored.fields[0].label.fa, 'تلفن دفتر')
  assert.deepEqual(restored.fields[0].settings.position, { x: 160, y: 210 })
  assert.equal(restored.fields[0].settings.demo.primary, '0215555000')
  const removed = sandbox.removeSandboxPhone(restored, 'phone-instance-1')
  assert.deepEqual(removed.fields.map(field => field.id), ['phone-instance-2'])
  assert.equal(sandbox.saveSandboxForm(storage, removed), true)
  assert.equal(sandbox.loadSandboxForm(storage).fields.length, 1)
  assert.equal(sandbox.restoreSandboxForm('{invalid'), null)
  assert.equal(sandbox.restoreSandboxForm(JSON.stringify({ ...form, fields: [form.fields[0], form.fields[0]] })), null)
  assert.equal(sandbox.saveSandboxForm({ setItem: () => { throw new Error('blocked') } }, form), false)
})

test('managed forms retain types, nested panel structure, ordering, dimensions and legacy phone data independently', () => {
  const preset = { id: 'contact.phone', componentId: 'base-form.value-list', title: { fa: 'تلفن', en: 'Phone', zh: '电话' }, schemaKind: 'valueList', labelPolicy: 'editable', allowedFormTypes: ['operational', 'hybrid'] }
  const legacyPhone = sandbox.addSandboxPhone(sandbox.emptySandboxForm(), preset, 'legacy-phone')
  const legacyRaw = JSON.stringify({ ...legacyPhone, mode: 'combined', sections: [{ id: 'sandbox.editor', kind: 'editor' }] })
  const values = new Map([[sandbox.sandboxStorageKey, legacyRaw], ['laboratory-existing-key', 'untouched']])
  const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) }
  const migrated = sandbox.loadManagedForms(storage)
  assert.equal(migrated.forms[0].mode, 'hybrid')
  assert.equal(migrated.forms[0].fields[0].id, 'legacy-phone')
  assert.equal(migrated.forms[0].sections[0].parentId, null)
  let form = sandbox.createManagedForm('form-1', 'فرم سفارش', 'operational')
  assert.deepEqual(form.sections, [])
  assert.deepEqual(form.fields, [])
  const title = name => ({ fa: name, en: name, zh: name })
  form = sandbox.addSandboxPanel(form, 'root-a', title('A'))
  form = sandbox.addSandboxPanel(form, 'root-b', title('B'))
  form = sandbox.addSandboxPanel(form, 'child-c', title('C'), 'root-a')
  form = sandbox.addSandboxPanel(form, 'child-d', title('D'), 'root-a', 'grid')
  form = { ...form, layout: { direction: 'horizontal', gap: 12 } }
  form = sandbox.updateSandboxPanel(form, 'root-a', { title: title('عنوان ویرایش‌شده'), layout: { direction: 'horizontal', gap: 12 }, initialSize: { width: 720, height: 420 } })
  form = sandbox.updateSandboxPanel(form, 'child-c', { layout: { direction: 'vertical', gap: 12 } })
  form = sandbox.addSandboxPhone(form, preset, 'new-phone', 'child-c')
  form = sandbox.moveSandboxPanel(form, 'root-b', null, 0)
  assert.deepEqual(sandbox.sandboxPanelChildren(form, null).map(panel => panel.id), ['root-b', 'root-a'])
  form = sandbox.moveSandboxPanel(form, 'child-d', 'root-b')
  assert.equal(form.sections.find(panel => panel.id === 'child-d').parentId, 'root-b')
  form = sandbox.moveSandboxPanel(form, 'child-d', 'root-a', 0)
  assert.deepEqual(sandbox.sandboxPanelChildren(form, 'root-a').map(panel => panel.id), ['child-d', 'child-c'])
  assert.throws(() => sandbox.moveSandboxPanel(form, 'root-a', 'child-c'), /descendants/)
  assert.throws(() => sandbox.moveSandboxPanel(form, 'root-a', 'missing'), /descendants/)
  assert.equal(sandbox.saveManagedForm(storage, form), true)
  const report = sandbox.createManagedForm('form-2', 'گزارش', 'reporting')
  const hybrid = sandbox.createManagedForm('form-3', 'ترکیبی', 'hybrid')
  assert.equal(sandbox.saveManagedForm(storage, report), true)
  assert.equal(sandbox.saveManagedForm(storage, hybrid), true)
  const renamed = { ...form, title: title('نام جدید') }
  assert.equal(sandbox.saveManagedForm(storage, renamed), true)
  const reopened = sandbox.loadManagedForms({ ...storage })
  assert.equal(reopened.forms.length, 4)
  assert.deepEqual(reopened.forms.find(item => item.id === 'form-1'), renamed)
  assert.deepEqual(reopened.forms.find(item => item.id === 'form-2'), report)
  assert.deepEqual(reopened.forms.find(item => item.id === 'form-3'), hybrid)
  assert.equal(reopened.activeFormId, 'form-1')
  assert.equal(values.get(sandbox.sandboxStorageKey), legacyRaw)
  assert.equal(values.get('laboratory-existing-key'), 'untouched')
  const removed = sandbox.removeSandboxPanel(renamed, 'root-a')
  assert.deepEqual(removed.sections.map(panel => panel.id), ['root-b'])
  assert.equal(removed.fields.length, 0)
  const cyclic = { ...form, sections: form.sections.map(panel => panel.id === 'root-a' ? { ...panel, parentId: 'child-c' } : panel) }
  assert.equal(sandbox.restoreSandboxForm(JSON.stringify(cyclic)), null)
  assert.equal(sandbox.restoreSandboxForm(JSON.stringify({ ...form, fields: [{ ...form.fields[0], sectionId: 'missing' }] })), null)
  values.set(sandbox.managedFormsStorageKey, '{invalid')
  assert.equal(sandbox.saveManagedForm(storage, report), false)
  assert.equal(values.get(sandbox.managedFormsStorageKey), '{invalid')
})
